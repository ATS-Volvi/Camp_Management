/**
 * Find a recipe match using exact then fuzzy matching on dish name.
 */
export function findRecipe(dishName: string): RecipeIngredient[] | null {
  const normalize = (s: string) => s.toLowerCase().trim().replace(/&/g, "and").replace(/\s+/g, " ");
  const normalizedSearch = normalize(dishName);

  // Exact match first
  for (const key of Object.keys(DISH_RECIPES)) {
    if (normalize(key) === normalizedSearch) return DISH_RECIPES[key];
  }

  // Partial match
  for (const key of Object.keys(DISH_RECIPES)) {
    const nk = normalize(key);
    if (normalizedSearch.includes(nk) || nk.includes(normalizedSearch)) {
      return DISH_RECIPES[key];
    }
  }

  return null;
}
